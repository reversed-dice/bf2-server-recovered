void RadioGLComp::playFailMessage(bool b)
{
    if (!is1P())
        return;

    if (!b)
        return;

    if (!getFailMessageEnabled())
        return;

    std::string msg = m_template->getFailMessage();
    if (!msg.empty()) {
        if (m_object) {
            IPlayer* player = m_object->getPlayer();
            if (player) {
                if ((gameLogic->isSinglePlayer() && player->isAIPlayer()) || playerManager->getLocalPlayer() == player) {
                    game->radioMessage(10, msg, player, player->getID(), true, false);
                }
            }
        }
        setFailMessageEnabled(false);
    }
}

